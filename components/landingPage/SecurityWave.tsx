export default function AnimatedSVG() {
    const mouseX = useMotionValue(0);
    const mouseY = useMotionValue(0);

    

    return (
        <svg width="487" height="418" viewBox="0 0 487 418" fill="none" overflow="visible">
            {paths.map((d, i) => {
                const isTopLayer = i === 0;
                const isSecondLayer = i === 1;

                const baseOffset =
                    isTopLayer ? -35 :
                        isSecondLayer ? 35 :
                            0;

                return (
                    <motion.path
                        key={i}
                        d={d}
                        initial={{ y: baseOffset }}
                        stroke="white"
                        strokeWidth="1 7"
                        strokeDasharray={isTopLayer ? "3 2" : "1 7"}
                        style={{
                            y: useTransform(mouseY, v => v + baseOffset),
                            x: useTransform(mouseX, v => v * (i % 3 === 0 ? 0.5 : 0.2)),
                        }}
                        animate={{
                            y: isTopLayer || isSecondLayer
                                ? [baseOffset, baseOffset - 4, baseOffset + 4, baseOffset]
                                : 0,

                            // Only animate dash for dotted layers
                            strokeDashoffset: isTopLayer ? 0 : [0, 40],
                        }}
                        transition={{
                            y: {
                                duration: 6,
                                repeat: Infinity,
                                ease: "easeInOut",
                            },
                            strokeDashoffset: {
                                duration: 8,
                                repeat: Infinity,
                                ease: "linear",
                            },
                        }}
                        whileHover={{
                            stroke: "#fdfdfdff",
                            strokeWidth: 2,
                        }}
                    />
                );
            })}
        </svg>
    );
}
